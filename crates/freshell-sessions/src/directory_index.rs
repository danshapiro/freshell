/// Reconciliation sweep interval. With the session watcher handling the
/// common case (~98.2% of changes detected via inotify), this TTL is a
/// safety net for the ~1.8% of events the watcher misses. Previously 1s
/// (continuous polling); raised to 15 minutes now that the watcher
/// provides sub-second freshness for the common case.
const DEFAULT_TTL: Duration = Duration::from_secs(15 * 60);

/// One session, enumerated by a [`SessionSource`]. Provider-agnostic — the
/// superset of fields `crates/freshell-server/src/session_directory.rs`'s
/// `DirItem` needs from the parse layer (everything EXCEPT the per-request
/// fields `archived` / `is_running` / the search annotations, which are
/// overlaid after the snapshot, never cached).
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct IndexedSession {
    pub session_id: String,
    /// A former provider identity that remains readable for user-owned
    /// overrides and metadata after a canonical-identity migration.  It is
    /// intentionally absent for Claude subagents: their embedded parent id
    /// was never an independent child identity and must not make a parent's
    /// settings spill onto every child.
    #[serde(default)]
    pub legacy_session_id: Option<String>,
    pub provider: String,
    pub project_path: String,
    pub title: Option<String>,
    /// Node's cached parse-layer `titleSource` (`ParsedSessionTitleSource`,
    /// `server/coding-cli/types.ts:100` — sole variant `'provider-generated'`,
    /// so a bool is the faithful shape; carried per cache entry at
    /// `session-indexer.ts:418` and fed into `applyOverride` at `:1186`):
    /// `true` iff [`Self::title`] was generated by the provider itself.
    /// `#[serde(default)]` so a persisted parse-cache written before this
    /// field existed still deserializes (as `false`, the pre-existing view).
    #[serde(default)]
    pub title_provider_generated: bool,
    pub summary: Option<String>,
    pub first_user_message: Option<String>,
    /// Mirror of Node's ParsedSessionTitleSource for the parsed (pre-override) title.
    /// The auto-title pipeline only compares against "provider-generated"
    /// (server/auto-title.ts:88). Mapping per provider:
    /// - **claude**: `"provider-generated"` if the title came from a provider-authored
    ///   record (custom-title, agent-name, or generated summary record with `type:'summary'`).
    ///   `None` otherwise (title derived from first user message).
    /// - **codex**: `None` (no provider-authored titles in codex transcripts).
    /// - **amplifier**: `"provider-generated"` if the session has an AI-generated name
    ///   (Amplifier's own session title). `None` if unnamed.
    /// - **opencode**: `"provider-generated"` iff the stored session title
    ///   is a real name -- not blank and not one of opencode's default
    ///   placeholders (`New session - `/`Child session - ` plus the legacy
    ///   capital-S `New Session - `, each followed by the 24-char ISO
    ///   stamp; see `parse::is_opencode_placeholder_title`). opencode
    ///   names parent sessions itself after the first exchange. `None` for
    ///   placeholder-titled sessions (those instead carry
    ///   `first_user_message` for the first-message/AI rungs).
    pub title_source: Option<String>,
    pub last_activity_at: i64,
    pub created_at: Option<i64>,
    pub cwd: Option<String>,
    /// Task 18: the transcript-parsed git branch (`ParsedSessionMeta::git_branch`,
    /// `meta.rs` -- claude/codex record it; opencode's direct lister does not).
    /// Consumed by `freshell-server`'s auto-title sweep as the FALLBACK under
    /// the live-git branch when refreshing terminal metadata (Node's
    /// `applySessionMetadata`: `session.gitBranch ?? current.branch`,
    /// `terminal-metadata-service.ts:195`). `#[serde(default)]` so any
    /// pre-Task-18 serialized snapshot still deserializes.
    #[serde(default)]
    pub git_branch: Option<String>,
    pub is_subagent: bool,
    pub is_non_interactive: bool,
    /// SESSION-07: the on-disk transcript this session was parsed from, when
    /// the source is a discrete per-session file (claude/codex). `None` for
    /// direct-listed sources with no stable per-session file (opencode's
    /// single sqlite db) -- those sessions are simply unsearchable at the
    /// `userMessages`/`fullText` tiers (title-tier metadata search still
    /// works for every provider, since it never reads this field). Consumed
    /// by `crates/freshell-server/src/session_directory.rs`'s file-tier
    /// search to locate the transcript to scan
    /// (`server/session-directory/service.ts`'s `sourceFiles` lookup map,
    /// `service.ts:164-173`).
    pub source_file: Option<PathBuf>,
}

impl IndexedSession {
    /// `provider:sessionId` — the sort/override key (`buildSessionKey`,
    /// `session-directory/service.ts:36-38`; matches `DirItem::key()`).
    pub fn key(&self) -> String {
        format!("{}:{}", self.provider, self.session_id)
    }
}

/// One discovered file: its absolute path plus the stat facts (`mtime`/`size`)
/// [`SessionIndex`]'s incremental cache uses to decide whether it needs
/// re-parsing. Stat-only — no file content is read to produce this.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileStat {
    pub path: PathBuf,
    /// Milliseconds since the Unix epoch (`mtime`'s coarsest reliable unit
    /// across platforms). Compared alongside `size` (not alone) because some
    /// filesystems have mtime resolution coarser than a fast test/edit cycle.
    pub mtime_ms: i64,
    pub size: u64,
}

/// A provider's session enumeration source (claude/codex/opencode). Batch B
/// ships [`ClaudeSource`] only; codex/opencode are additive `SessionSource`
/// impls for Batch C — [`SessionIndex`] composes any number of sources
/// without changing shape.
///
/// Split into `discover` (cheap: stat every visible file) + `parse` (expensive:
/// read + parse ONE file) so [`SessionIndex`]'s incremental cache can re-parse
/// only what actually changed, instead of re-parsing everything on every
/// refresh. A third stat path, [`Self::stat_scoped`], serves watcher-scoped
/// dirty marks and MUST key the cache identically to `discover`'s stats.
pub trait SessionSource: Send + Sync {
    /// Enumerate every file this provider can currently see — stat only
    /// (path/mtime/size), no parsing. Corruption-tolerant (an unreadable
    /// directory yields fewer entries, never panics).
    fn discover(&self) -> Vec<FileStat>;

    /// Parse one file (previously returned by [`Self::discover`]) into a
    /// session. `None` means the file is unreadable OR was parsed and
    /// EXCLUDED (e.g. the R10b cwd-less rule) — [`SessionIndex`] caches an
    /// exclusion the same as a successful parse, so an excluded file is
    /// never re-parsed unless it actually changes. Corruption-tolerant —
    /// never panics.
    fn parse(&self, path: &Path) -> Option<IndexedSession>;

    /// Batch C: direct-listed sources (opencode's single sqlite db, which
    /// enumerates MANY sessions in ONE query rather than one file per
    /// session) can't fit the per-file `discover`/`parse` cache — there's no
    /// stable per-session path to key a [`FileEntry`] by. Instead, a
    /// direct-listed source returns `Some(token)` here: a cheap-to-compute
    /// value (e.g. a file mtime) that changes if-and-only-if the underlying
    /// data might have changed. [`SessionIndex`] calls this every sweep and
    /// only calls [`Self::direct_list`] (the expensive query) when the token
    /// differs from the one cached from the last successful listing.
    ///
    /// `None` (the default) means "this is a file-based source" —
    /// `discover`/`parse` are used instead, and this method/`direct_list` are
    /// never called.
    fn direct_change_token(&self) -> Option<i64> {
        None
    }

    /// The expensive full listing for a direct-listed source, called ONLY
    /// when [`Self::direct_change_token`] changed since the last successful
    /// call. `Err` preserves whatever [`SessionIndex`] cached from the last
    /// successful listing (e.g. a locked/mid-write sqlite db) instead of
    /// dropping that provider's sessions from the snapshot.
    fn direct_list(&self) -> Result<Vec<IndexedSession>, String> {
        Ok(Vec::new())
    }

    /// Per-sweep health probe for a direct-listed source, consulted on EVERY
    /// sweep — including when [`Self::direct_change_token`] is UNCHANGED.
    /// Node parity: `refreshDirectProvider()` runs on every full scan and
    /// records/clears `scanFailures` per attempt (`session-indexer.ts:1457`,
    /// `:1070-1082`), so its failure evidence is never older than one scan.
    /// The mtime change-token gates only the expensive re-QUERY (the session
    /// DATA cache) — it must never gate the HEALTH signal, because a database
    /// can become locked or unreadable (e.g. `chmod`) without either mtime
    /// moving. `Err` records a scan failure (cached sessions preserved); `Ok`
    /// clears it. Default `Ok` for file-based sources (never called).
    fn direct_health_check(&self) -> Result<(), String> {
        Ok(())
    }

    /// Provider identity for scan-failure reporting (`getScanFailures` parity).
    /// `None` (default) = this source does not participate in failure tracking.
    fn provider_name(&self) -> Option<&'static str> {
        None
    }

    /// Discovery with ROOT-listing failure propagation (Node parity: a
    /// throwing `listSessionFiles()` is RECORDED in scanFailures —
    /// `session-indexer.ts:1250-1262` — never silently treated as empty).
    /// Default wraps the infallible `discover()` for test sources.
    fn discover_checked(&self) -> Result<Vec<FileStat>, std::io::Error> {
        Ok(self.discover())
    }

    /// Fold-aware stat for a watcher-scoped dirty path. The incremental
    /// cache key written for `path` comes from whatever this returns, so a
    /// source whose discover stats fold sibling state into the cache key
    /// (amplifier's sidecar mtimes) MUST fold identically here — otherwise
    /// the discover and scoped paths write different cache keys for the same
    /// file (raw-vs-folded thrash + frozen recency, design lines 77-83).
    /// `None` means the file is gone/unreadable and prunes the entry — a
    /// source override must therefore return None when ITS canonical file is
    /// missing regardless of surviving sidecars (never resurrect a ghost).
    fn stat_scoped(&self, path: &Path) -> Option<FileStat> {
        stat_file(path)
    }
}

/// Open a provider ROOT directory for the SINGLE-PASS checked traversals
/// below: a MISSING root (`NotFound`/`NotADirectory`) is a genuine empty
/// (an absent provider — matches Node's ENOENT tolerance, `Ok(None)`), while
/// any other open failure (EACCES/EIO/...) PROPAGATES so the sweep records
/// it as a scan failure instead of silently serving an empty listing.
///
/// This replaces the earlier disposable `read_dir` PREFLIGHT
/// (`ensure_root_listable`) that was followed by a second, error-swallowing
/// `read_dir` for the actual traversal — a TOCTOU window where a failure
/// between the two calls (or a per-entry iterator error during the second)
/// came back as `Ok(empty)`, CLEARING the provider's scan failure and
/// pruning its cached sessions from a sweep that never actually listed
/// anything. The traversals now consume THIS handle directly (one
/// `read_dir`, no window) and propagate per-entry iterator errors with `?`.
/// `pub(crate)` so `amplifier.rs`'s source can reuse it.
pub(crate) fn open_root_dir(root: &Path) -> Result<Option<std::fs::ReadDir>, std::io::Error> {
    match std::fs::read_dir(root) {
        Ok(entries) => Ok(Some(entries)),
        Err(e)
            if matches!(
                e.kind(),
                std::io::ErrorKind::NotFound | std::io::ErrorKind::NotADirectory
            ) =>
        {
            Ok(None)
        }
        Err(e) => Err(e),
    }
}

/// Claude source: walks `<claude_home>/projects/*/…*.jsonl` (top-level =
/// sessions, `<project>/<session>/subagents/*.jsonl` = subagents). A faithful
/// lift of `session_directory.rs::list_claude_sessions` — that function is
/// KEPT (unmodified) as the differential-oracle reference B-T1 pins this
/// against, so the two implementations intentionally coexist during the
/// migration.
pub struct ClaudeSource {
    claude_home: PathBuf,
}

impl ClaudeSource {
    pub fn new(claude_home: PathBuf) -> Self {
        Self { claude_home }
    }

    /// Convenience: discover + parse every currently-visible file in one
    /// call, ignoring any incremental cache. Production code never calls
    /// this — it goes through [`SessionIndex`]'s incremental sweep — but it's
    /// the natural shape for the differential-oracle (B-T1) and perf tests
    /// that want a single one-shot full scan.
    pub fn scan(&self) -> Vec<IndexedSession> {
        self.discover()
            .into_iter()
            .filter_map(|stat| self.parse(&stat.path))
            .collect()
    }
}

impl SessionSource for ClaudeSource {
    fn discover(&self) -> Vec<FileStat> {
        discover_claude_home(&self.claude_home).unwrap_or_default()
    }

    fn provider_name(&self) -> Option<&'static str> {
        Some("claude")
    }

    /// Root-listing failure propagation: an unlistable `<claude_home>/projects`
    /// (EACCES/EIO — not a merely-absent one) is a scan failure, never a
    /// silent empty listing. SINGLE-PASS: the same `read_dir` handle that
    /// fails here is the one the traversal consumes (no disposable preflight,
    /// no TOCTOU window), and root iterator-entry errors propagate too.
    /// Per-project/nested errors stay tolerant.
    fn discover_checked(&self) -> Result<Vec<FileStat>, std::io::Error> {
        discover_claude_home(&self.claude_home)
    }

    fn parse(&self, path: &Path) -> Option<IndexedSession> {
        // A file directly inside a `subagents/` directory is a subagent
        // transcript (mirrors `scan_claude_home`'s walk structure, which
        // KNOWS this from the directory it's currently iterating — here it's
        // re-derived from the path alone since `parse` receives just a path).
        let force_subagent = path
            .parent()
            .and_then(|p| p.file_name())
            .and_then(|n| n.to_str())
            == Some("subagents");
        parse_claude_file(path, force_subagent)
    }
}

/// Stat (not parse) every `<claude_home>/projects/*/…*.jsonl` file, in the
/// same discovery order `scan_claude_home` used to walk them (sorted
/// directory entries — determinism; readdir order is filesystem-dependent).
///
/// SINGLE-PASS root traversal: the ONE `read_dir` opened by [`open_root_dir`]
/// is the one iterated, and per-entry iterator errors propagate (`?`) — a
/// root that fails to open OR fails mid-iteration is an `Err` (recorded as a
/// scan failure by the sweep), never a silent `Ok(empty)`. A MISSING root is
/// a genuine empty. Per-project/nested errors stay tolerant (Node parity).
fn discover_claude_home(claude_home: &Path) -> Result<Vec<FileStat>, std::io::Error> {
    let projects_dir = crate::provider_layout::ClaudeLayout.session_root(claude_home);
    let Some(project_entries) = open_root_dir(&projects_dir)? else {
        return Ok(Vec::new());
    };

    let mut stats = Vec::new();
    let mut project_dirs: Vec<PathBuf> = Vec::new();
    for entry in project_entries {
        project_dirs.push(entry?.path());
    }
    project_dirs.sort(); // determinism (readdir order is filesystem-dependent)

    for project_dir in project_dirs {
        if !project_dir.is_dir() {
            continue;
        }
        let Ok(entries) = std::fs::read_dir(&project_dir) else {
            continue;
        };
        let mut names: Vec<PathBuf> = entries.filter_map(|e| e.ok()).map(|e| e.path()).collect();
        names.sort();

        for entry_path in names {
            if entry_path.extension().and_then(|s| s.to_str()) == Some("jsonl") {
                if let Some(stat) = stat_file(&entry_path) {
                    stats.push(stat);
                }
                continue;
            }
            // Subdirectory: discover `<entry>/subagents/*.jsonl`.
            if entry_path.is_dir() {
                let subagents = entry_path.join("subagents");
                if let Ok(subs) = std::fs::read_dir(&subagents) {
                    let mut sub_paths: Vec<PathBuf> =
                        subs.filter_map(|e| e.ok()).map(|e| e.path()).collect();
                    sub_paths.sort();
                    for sub in sub_paths {
                        if sub.extension().and_then(|s| s.to_str()) == Some("jsonl") {
                            if let Some(stat) = stat_file(&sub) {
                                stats.push(stat);
                            }
                        }
                    }
                }
            }
        }
    }
    Ok(stats)
}

/// `fs::metadata` a single file into a [`FileStat`]. `None` on any stat
/// failure (e.g. a file deleted between `read_dir` and `metadata` — the same
/// tolerance every other discovery step in this module already has).
fn stat_file(path: &Path) -> Option<FileStat> {
    let meta = std::fs::metadata(path).ok()?;
    let mtime_ms = meta
        .modified()
        .ok()
        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0);
    Some(FileStat {
        path: path.to_path_buf(),
        mtime_ms,
        size: meta.len(),
    })
}

/// Read + parse one claude transcript file into an [`IndexedSession`].
/// Corruption-tolerant (the parser never panics); an unreadable file is
/// skipped (`None`). Mirrors `session_directory.rs::parse_claude_file`
/// byte-for-byte (lossy-UTF-8 read, R10b cwd-less exclusion).
fn parse_claude_file(path: &Path, force_subagent: bool) -> Option<IndexedSession> {
    let content = String::from_utf8_lossy(&std::fs::read(path).ok()?).into_owned();
    let fallback = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("")
        .to_string();
    let opts = ParseSessionOptions {
        fallback_session_id: Some(fallback.clone()),
        ..Default::default()
    };
    let meta = parse_session_content(&content, &opts);
    // R10b: never index a session with no resolvable `cwd` (the ORIGINAL's
    // discovery-time gate, `session-indexer.ts:756,1124`).
    meta.cwd.as_ref()?;
    let is_subagent = force_subagent || meta.is_subagent.unwrap_or(false);
    // Claude's provider identity is the transcript filename. In particular,
    // real subagent records embed their PARENT's `sessionId`; trusting that
    // field collapses every child onto the parent key. Select the provider's
    // canonical identity at construction rather than first accepting parsed
    // metadata and then overwriting it below.
    //
    // A non-subagent transcript whose old embedded id differs from its file
    // name keeps a compatibility alias for user-owned overrides/metadata.
    // Children deliberately do not: their old embedded id is the parent and
    // applying it would incorrectly copy the parent's settings to each child.
    let legacy_session_id = (!is_subagent)
        .then_some(meta.session_id.as_deref())
        .flatten()
        .filter(|session_id| *session_id != fallback)
        .map(str::to_owned);
    Some(item_from_meta(
        &meta,
        "claude",
        fallback,
        force_subagent,
        Some(path.to_path_buf()),
        legacy_session_id,
    ))
}

fn item_from_meta(
    meta: &ParsedSessionMeta,
    provider: &str,
    session_id: String,
    force_subagent: bool,
    source_file: Option<PathBuf>,
    legacy_session_id: Option<String>,
) -> IndexedSession {
    IndexedSession {
        session_id,
        legacy_session_id,
        provider: provider.to_string(),
        project_path: meta.cwd.clone().unwrap_or_else(|| "unknown".to_string()),
        title: meta.title.clone(),
        title_provider_generated: meta.title_provider_generated,
        summary: meta.summary.clone(),
        first_user_message: meta.first_user_message.clone(),
        title_source: meta.title_source.clone(),
        last_activity_at: meta.last_activity_at.unwrap_or(0).max(0),
        created_at: meta.created_at,
        cwd: meta.cwd.clone(),
        git_branch: meta.git_branch.clone(),
        is_subagent: force_subagent || meta.is_subagent.unwrap_or(false),
        is_non_interactive: meta.is_non_interactive.unwrap_or(false),
        source_file,
    }
}

