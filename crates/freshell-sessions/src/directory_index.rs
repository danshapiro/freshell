/// Stat every `.jsonl` under `<codex_home>/sessions`, recursively.
///
/// SINGLE-PASS root traversal: the ONE `read_dir` opened by [`open_root_dir`]
/// is the one iterated, and per-entry iterator errors propagate (`?`) — a
/// root that fails to open OR fails mid-iteration is an `Err` (recorded as a
/// scan failure by the sweep), never a silent `Ok(empty)`. A MISSING root is
/// a genuine empty. NESTED directories stay tolerant via
/// [`walk_jsonl_recursive`] (Node parity: `walkJsonlFiles`).
fn discover_codex_sessions(codex_home: &Path) -> Result<Vec<FileStat>, std::io::Error> {
    let root = crate::provider_layout::CodexLayout.session_root(codex_home);
    let Some(entries) = open_root_dir(&root)? else {
        return Ok(Vec::new());
    };
    let mut paths: Vec<PathBuf> = Vec::new();
    for entry in entries {
        paths.push(entry?.path());
    }
    paths.sort(); // determinism (readdir order is filesystem-dependent)
    let mut stats = Vec::new();
    for path in paths {
        if path.is_dir() {
            walk_jsonl_recursive(&path, &mut stats);
        } else if path.extension().and_then(|s| s.to_str()) == Some("jsonl") {
            if let Some(stat) = stat_file(&path) {
                stats.push(stat);
            }
        }
    }
    Ok(stats)
}

/// Recursively stat every `.jsonl` under `dir`, sorted (per directory level)
/// for determinism — readdir order is filesystem-dependent. Mirrors
/// `walkJsonlFiles` (`providers/codex.ts:423-436`): unbounded recursion,
/// corruption-tolerant (an unreadable directory yields fewer entries, never
/// panics). NESTED levels only — the root level is
/// [`discover_codex_sessions`]'s single-pass checked traversal.
fn walk_jsonl_recursive(dir: &Path, out: &mut Vec<FileStat>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    paths.sort(); // determinism (readdir order is filesystem-dependent)
    for path in paths {
        if path.is_dir() {
            walk_jsonl_recursive(&path, out);
        } else if path.extension().and_then(|s| s.to_str()) == Some("jsonl") {
            if let Some(stat) = stat_file(&path) {
                out.push(stat);
            }
        }
    }
}

/// Read + parse one codex rollout file into an [`IndexedSession`].
/// Corruption-tolerant (the parser never panics); an unreadable file is
/// skipped (`None`). Enforces the SAME R10b cwd-less exclusion the claude
/// path does — `session-indexer.ts`'s discovery-time `if (!meta.cwd) continue`
/// gate (:756, :1124) applies to every provider, not just claude.
fn parse_codex_file(path: &Path) -> Option<IndexedSession> {
    let content = String::from_utf8_lossy(&std::fs::read(path).ok()?).into_owned();
    let meta = parse_codex_session_content(&content);
    meta.cwd.as_ref()?;
    let fallback = extract_codex_session_id_from_filename(path);
    let session_id = meta.session_id.clone().unwrap_or(fallback);
    Some(item_from_meta(
        &meta,
        "codex",
        session_id,
        false,
        Some(path.to_path_buf()),
        None,
    ))
}

/// `extractSessionIdFromFilename` (`providers/codex.ts:417-420`): the
/// basename minus `.jsonl`, or — if the basename contains one — the embedded
/// canonical-looking UUID substring (codex rollout filenames look like
/// `rollout-2026-03-01T00-00-06-<uuid>.jsonl`).
fn extract_codex_session_id_from_filename(path: &Path) -> String {
    let base = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("")
        .to_string();
    find_uuid_substring(&base).unwrap_or(base)
}

/// First substring matching
/// `[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}`
/// — no anchoring, no version/variant nibble constraint (unlike
/// `is_canonical_claude_session_id`, this mirrors the codex regex exactly).
fn find_uuid_substring(s: &str) -> Option<String> {
    let bytes = s.as_bytes();
    let groups = [8usize, 4, 4, 4, 12];
    'start: for start in 0..bytes.len() {
        let mut pos = start;
        for (gi, &len) in groups.iter().enumerate() {
            if pos + len > bytes.len() || !bytes[pos..pos + len].iter().all(u8::is_ascii_hexdigit) {
                continue 'start;
            }
            pos += len;
            if gi + 1 < groups.len() {
                if bytes.get(pos) != Some(&b'-') {
                    continue 'start;
                }
                pos += 1;
            }
        }
        return Some(s[start..pos].to_string());
    }
    None
}

/// OpenCode source: direct-listed from `<data_home>/opencode.db` (one sqlite
/// query enumerates every root session, unlike the file-per-session
/// claude/codex layout) — a thin wrapper over [`OpencodeProvider`]
/// (`crate::parse::opencode`), which is itself the faithful port of
/// `OpencodeProvider.listSessionsDirect`. Implements the
/// `direct_change_token`/`direct_list` hooks instead of `discover`/`parse`
/// (see [`SessionSource`]'s doc comment) — `discover`/`parse` return
/// empty/`None` and are never called in practice.
pub struct OpencodeSource {
    provider: crate::parse::OpencodeProvider,
}

impl OpencodeSource {
    pub fn new(data_home: PathBuf) -> Self {
        Self {
            provider: crate::parse::OpencodeProvider::new(data_home),
        }
    }

    /// Convenience: one-shot listing, ignoring any incremental cache.
    /// Test/perf use only — mirrors `ClaudeSource::scan()`/`CodexSource::scan()`,
    /// but goes through `direct_list()` since this source has no per-file
    /// discover/parse.
    pub fn scan(&self) -> Vec<IndexedSession> {
        self.direct_list().unwrap_or_default()
    }
}

impl SessionSource for OpencodeSource {
    fn discover(&self) -> Vec<FileStat> {
        Vec::new()
    }

    fn parse(&self, _path: &Path) -> Option<IndexedSession> {
        None
    }

    fn provider_name(&self) -> Option<&'static str> {
        Some("opencode")
    }

    fn direct_change_token(&self) -> Option<i64> {
        // The WAL wrinkle is load-bearing: sqlite in WAL mode (opencode's
        // default) can satisfy a write by appending to `opencode.db-wal`
        // ALONE, leaving `opencode.db`'s own mtime unchanged until the next
        // checkpoint. Taking the max of both files' mtimes (0 for whichever
        // doesn't exist) means a WAL-only write still changes the token.
        let [db, wal] = self.provider.watched_database_paths();
        let db_mtime = file_mtime_ms(&db).unwrap_or(0);
        let wal_mtime = file_mtime_ms(&wal).unwrap_or(0);
        Some(db_mtime.max(wal_mtime))
    }

    fn direct_list(&self) -> Result<Vec<IndexedSession>, String> {
        let listing = self
            .provider
            .list_sessions(now_ms())
            .map_err(|e| e.to_string())?;
        Ok(listing
            .sessions
            .into_iter()
            .map(opencode_session_to_indexed)
            .collect())
    }

    /// Per-sweep health probe (see the trait doc): the db must still be
    /// OPENABLE and its schema page READABLE through the exact open path
    /// `direct_list` uses -- a locked/`chmod`ed/corrupted db fails here even
    /// when its mtime (the change token) never moved. A MISSING db stays
    /// healthy-absent, matching `list_sessions`'s `MissingDb` tolerance.
    fn direct_health_check(&self) -> Result<(), String> {
        self.provider.health_check().map_err(|e| e.to_string())
    }
}

fn opencode_session_to_indexed(s: crate::parse::OpencodeSession) -> IndexedSession {
    // A non-placeholder opencode title is opencode's OWN session name
    // (opencode retitles sessions itself after the first exchange).
    // Surface it as provider-generated so the auto-title ladder yields to
    // it: `should_generate_ai` short-circuits (freshell-server/auto_title.rs)
    // and the sweep's shadow guard lets it win over stale dir/first-message
    // override rows (auto_title_sweep.rs::overlay_session_title). Deliberate
    // mainline deviation from the retired Node reference, which never
    // populated titleSource or firstUserMessage for opencode.
    let provider_named = s
        .title
        .as_deref()
        .is_some_and(|t| !t.trim().is_empty() && !crate::parse::is_opencode_placeholder_title(t));
    IndexedSession {
        session_id: s.session_id,
        legacy_session_id: None,
        provider: "opencode".to_string(),
        project_path: s.project_path,
        title: s.title,
        // bool twin of `title_source` -- same predicate, kept consistent
        // (see parse/claude.rs's identical convention).
        title_provider_generated: provider_named,
        // The opencode direct-lister has no text summary to offer (the
        // session table's summary_* columns are diff stats) -- None.
        summary: None,
        // Populated by the parse layer ONLY for sessions that still need
        // naming (bounded lookup) -- feeds the first-message/AI rungs.
        first_user_message: s.first_user_message,
        title_source: provider_named.then(|| "provider-generated".to_string()),
        last_activity_at: s.last_activity_at,
        created_at: s.created_at,
        // `OpencodeSession::cwd` is always present (`list_sessions` already
        // skips rows without one) — R10b is a structural non-issue here.
        cwd: Some(s.cwd),
        // The opencode direct-lister reads no git facts from the db -- None,
        // faithful to `listSessionsDirect`.
        git_branch: None,
        is_subagent: s.is_subagent.unwrap_or(false),
        is_non_interactive: s.is_non_interactive.unwrap_or(false),
        // SESSION-07: opencode is direct-listed from one sqlite db, not a
        // per-session file -- there is no stable path to scan, so this
        // provider is un-searchable at the `userMessages`/`fullText` tiers
        // (title-tier metadata search is unaffected).
        source_file: None,
    }
}

/// `fs::metadata(path).modified()` in milliseconds, `None` on any stat
/// failure (including "doesn't exist") — used by [`OpencodeSource`]'s change
/// token, which treats a missing file as mtime `0`.
fn file_mtime_ms(path: &Path) -> Option<i64> {
    stat_file(path).map(|s| s.mtime_ms)
}

/// The injected-clock parameter [`OpencodeProvider::list_sessions`] wants
/// (mirrors the reference's `Date.now()` fallback for a row with no
/// `time_updated`).
fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

/// One cached file's parse result, keyed by its absolute path in
/// [`SessionIndex`]'s `file_cache`. `item: None` caches a file that was
/// parsed and EXCLUDED (e.g. the R10b cwd-less rule) — so an excluded file is
/// stat'd every sweep but never re-parsed unless it actually changes.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
struct FileEntry {
    /// The file-backed source that discovered this path. Persisted so a root
    /// outage for one provider can retain only that provider's cache while
    /// healthy providers still prune deleted rows. Older cache entries omit
    /// this and are conservatively retained during any failed sweep until a
    /// healthy discovery assigns them a source.
    #[serde(default)]
    source_name: Option<String>,
    mtime_ms: i64,
    size: u64,
    item: Option<IndexedSession>,
}

/// The cached, TTL-refreshed session index composed from one or more
/// [`SessionSource`]s.
///
/// * The cheap path (fresh cache) never touches `.await` while holding the
///   `std::sync::Mutex` guard — the guard is dropped before any lock is even
///   contended, so it can never be held across an await point.
/// * **Stale-while-revalidate ("snapshot-swap").** A stale-but-PRESENT cache
///   is served immediately, and the actual re-scan runs DETACHED
///   (`tokio::spawn`) — no foreground caller ever waits on it. Production
///   forensics on a real ~13-15k session corpus measured `snapshot()`
///   sweeps taking up to 283s; the FIRST shipped version of this design
///   held a single `AsyncMutex` guard for a sweep's ENTIRE duration, so
///   every OTHER concurrent `snapshot()` caller (every foreground
///   `GET /api/session-directory` request, and the periodic
///   `spawn_sessions_sweep` poll) blocked on that same mutex for as long as
///   the sweep ran, even though a perfectly servable snapshot already
///   existed. Only a TRULY cold cache (nothing ever published — the very
///   first call, e.g. boot's `warm()`) still waits inline; there is nothing
///   else to serve. `refresh_lock`'s exclusivity (`try_lock_owned`) still
///   guarantees N concurrent stale-misses trigger exactly 1 sweep, matching
///   B-T5's original dedup guarantee — it now ALSO guarantees that sweep
///   never blocks a reader who already has something to read.
/// * The refresh (`refresh_snapshot`) runs inside `spawn_blocking`: `sources`
///   (an `Arc` refcount bump per source, not a deep clone of any scanned
///   data) and `file_cache` (an `Arc` refcount bump) are MOVED into the
///   blocking closure, so a multi-second full sweep never blocks the async
///   executor or any other in-flight request.
/// * The refresh is INCREMENTAL: `file_cache` persists across sweeps (it
///   outlives any single `snapshot()` call), so a sweep re-parses only a file
///   whose `(mtime, size)` changed since the LAST sweep — not every file,
///   every time. The `file_cache`'s own `std::sync::Mutex` is locked only
///   from inside the `spawn_blocking` closure (a fully synchronous context —
///   no `.await` ever runs while it's held).
pub struct SessionIndex {
    sources: Vec<Arc<dyn SessionSource>>,
    ttl: Duration,
    /// `Arc`-wrapped (not just `StdMutex`-wrapped) so a DETACHED background
    /// refresh task (`spawn_background_refresh`) can publish into it without
    /// holding a borrow of `&SessionIndex` for the task's lifetime.
    snapshot: Arc<StdMutex<Option<CachedSnapshot>>>,
    /// Exclusivity gate for "who is currently sweeping" -- `try_lock_owned`
    /// (never blocks the caller) decides who starts a sweep;
    /// `lock_owned().await` (blocks) is used ONLY by a caller racing another
    /// caller on a truly cold (nothing-published-yet) cache, where waiting
    /// for the other's result is correct because there is nothing else to
    /// serve. See the struct doc comment's "Stale-while-revalidate" bullet.
    refresh_lock: Arc<AsyncMutex<()>>,
    file_cache: Arc<StdMutex<HashMap<PathBuf, FileEntry>>>,
    /// Batch C: the per-source cache for direct-listed sources (opencode),
    /// keyed by the source's position in `sources` (fixed at construction, so
    /// an index is a stable, simpler key than source identity). Disjoint from
    /// `file_cache` -- a direct-listed source never touches it.
    direct_cache: Arc<StdMutex<HashMap<usize, DirectEntry>>>,
    /// Persistent parse-cache file path (`rust-session-cache.json`), or
    /// `None` to disable persistence entirely (e.g. no resolvable home).
    /// Read at construction to pre-populate `file_cache`; written back
    /// opportunistically after a sweep (see `Self::take_pending_save`).
    persist_path: Option<PathBuf>,
    /// `Arc`-wrapped for the same reason `snapshot` is: a detached
    /// background refresh needs to update the save-debounce bookkeeping
    /// without borrowing `&SessionIndex`.
    persist_state: Arc<StdMutex<PersistState>>,
    /// Paths marked dirty by an external watcher, keyed by path with the
    /// provider name that qualified the path. A dirty path is re-stat'd
    /// (and re-parsed if mtime/size changed) on the next refresh, even
    /// if the TTL hasn't expired yet.
    dirty_paths: Arc<StdMutex<HashMap<PathBuf, String>>>,
    /// Providers marked fully dirty (e.g. its root directory appeared/disappeared).
    /// Triggers a full discover() for that provider on next refresh.
    dirty_providers: Arc<StdMutex<HashSet<String>>>,
    /// Wake-up handoff for the check-to-unlock window (delta D5-1).
    /// `mark_dirty`/`mark_provider_dirty` store `true` AFTER enqueuing and
    /// BEFORE attempting `refresh_lock.try_lock()`, so a mark whose
    /// try-lock fails (a sweep — or a cold-cache awaiter — still holds the
    /// guard) is causally ordered before that holder's end-of-work consult.
    /// Every sweep iteration absorbs the flag at its start (a plain
    /// `store(false)`, paired with that iteration's later drain: every mark
    /// whose store preceded the absorb has its enqueue ordered before the
    /// drain, so the drain provably covers it) and every guard release is
    /// followed by a consult of the flag. See [`Self::perform_refresh`].
    wake_pending: Arc<AtomicBool>,
    /// When the last full reconciliation completed (all providers discovered).
    /// `None` means no full reconciliation has ever run. Used to ensure the
    /// TTL-based full sweep fires even when scoped refreshes keep the
    /// snapshot's `fetched_at` fresh.
    last_full_at: Arc<StdMutex<Option<Instant>>>,
    /// Monotonic generation counter, bumped on every snapshot publish.
    /// Subscribers (via `subscribe_changes`) wake on changes.
    change_tx: tokio::sync::watch::Sender<u64>,
    change_rx: tokio::sync::watch::Receiver<u64>,
    /// One-way refresh→watcher report (amplifier watch-reduction design,
    /// "Self-correction channel"). After a sweep that fully discovered
    /// amplifier, the watcher receives every amplifier session dir whose
    /// parsed metadata has `parent_id` absent (true roots). Amplifier
    /// IndexedSession rows publish `source_file: None` (amplifier.rs:415-419),
    /// so dirs are derived from the private `file_cache` KEYS (canonical
    /// metadata.json paths), never from published rows.
    amplifier_root_report: Arc<StdMutex<Option<tokio::sync::mpsc::UnboundedSender<Vec<PathBuf>>>>>,
    /// The startup watcher-ready barrier (amplifier watch-reduction Task
    /// 9): an OPTIONAL gate, fed by `SessionWatcher::startup_ready` (never
    /// installed when no session watcher runs — today's exact behavior).
    /// Consulted COLD-ONLY: while installed AND no snapshot has ever been
    /// published, the two publish entries (`run_refresh_inline` and the
    /// spawned task inside `spawn_background_refresh`) await readiness
    /// before sweeping, so the FIRST publish of the process is provably
    /// ordered after the watcher's startup arm pass settles. `Arc`-wrapped
    /// for the same reason `snapshot` is: the detached background refresh
    /// consults its own clone.
    startup_gate: Arc<StdMutex<Option<tokio::sync::watch::Receiver<bool>>>>,
}

/// One published sweep GENERATION: the snapshot items AND the scan-failure
/// set that same sweep produced, behind ONE lock. Publishing them as a unit
/// (and reading them through [`SessionIndex::snapshot_with_failures`]) is
/// what makes a coherent read possible — a consumer can never pair a
/// failed-scan empty snapshot with a subsequently cleared failure set (a
/// healthy-looking `ready + matches: []` lie), nor a recovered snapshot
/// with stale failures. The lock is only ever held for field reads/writes,
/// never across a sweep or an await point.
struct CachedSnapshot {
    items: Arc<Vec<IndexedSession>>,
    fetched_at: Instant,
    /// Providers whose listing attempt FAILED during the sweep that
    /// published THIS generation (`getScanFailures` parity — see
    /// [`SessionIndex::scan_failures`]).
    scan_failures: HashSet<String>,
}

/// Bookkeeping for the persistent parse-cache's opportunistic-save gating
/// (module doc comment's "Persistent parse cache" section).
#[derive(Default)]
struct PersistState {
    /// Files parsed (changed/new), confirmed stale file-cache entries pruned,
    /// or direct-listed sources re-queried since the last successful save --
    /// reset to 0 whenever a save happens.
    changed_since_save: u64,
    last_saved_at: Option<Instant>,
    /// Sticky "have we EVER saved" flag: the initial `warm()` build always
    /// persists once, regardless of how few files it touched (a home with
    /// fewer than `SAVE_CHANGED_THRESHOLD` sessions must still get its
    /// first-ever cache file, not wait for the 60s debounce or a 50-file
    /// burst that will never come).
    saved_once: bool,
}

impl SessionIndex {
    pub fn new(sources: Vec<Arc<dyn SessionSource>>) -> Self {
        Self::with_ttl(sources, DEFAULT_TTL)
    }

    pub fn with_ttl(sources: Vec<Arc<dyn SessionSource>>, ttl: Duration) -> Self {
        Self::with_ttl_and_cache_path(sources, ttl, default_persist_path())
    }

    /// Same as `Self::with_ttl`, but with an explicit (or disabled -- `None`)
    /// persistent parse-cache path instead of relying on
    /// `default_persist_path`'s environment-variable resolution. This is the
    /// dependency-injection seam that lets tests point at an isolated
    /// temp-dir cache file (deterministic, no global env var mutation, safe
    /// under the test harness's parallel execution) while `new`/`with_ttl`
    /// -- whose signatures `crates/freshell-server/src/main.rs` depends on
    /// unchanged -- keep today's exact call shape.
    pub fn with_ttl_and_cache_path(
        sources: Vec<Arc<dyn SessionSource>>,
        ttl: Duration,
        persist_path: Option<PathBuf>,
    ) -> Self {
        // Pre-populate the file cache from disk, if a persisted cache exists
        // and is readable/current -- `load_cache_file` is fully tolerant
        // (missing/corrupt/wrong-version all yield an empty map, never a
        // panic). The FIRST `refresh_snapshot` sweep re-validates every
        // loaded entry's (mtime, size) against a fresh `discover()` before
        // trusting it (the same incremental-cache logic that already
        // protects a warm in-memory cache) -- persistence only changes
        // WHERE the starting cache comes from, never how it's trusted.
        let file_cache = persist_path
            .as_deref()
            .map(load_cache_file)
            .unwrap_or_default();
        let (change_tx, change_rx) = tokio::sync::watch::channel(0u64);
        Self {
            sources,
            ttl,
            snapshot: Arc::new(StdMutex::new(None)),
            refresh_lock: Arc::new(AsyncMutex::new(())),
            file_cache: Arc::new(StdMutex::new(file_cache)),
            direct_cache: Arc::new(StdMutex::new(HashMap::new())),
            persist_path,
            persist_state: Arc::new(StdMutex::new(PersistState::default())),
            dirty_paths: Arc::new(StdMutex::new(HashMap::new())),
            dirty_providers: Arc::new(StdMutex::new(HashSet::new())),
            wake_pending: Arc::new(AtomicBool::new(false)),
            last_full_at: Arc::new(StdMutex::new(None)),
            change_tx,
            change_rx,
            amplifier_root_report: Arc::new(StdMutex::new(None)),
            startup_gate: Arc::new(StdMutex::new(None)),
        }
    }

    /// Providers whose MOST RECENT listing attempt failed (unsearchable, not
    /// empty) — `codingCliIndexer.getScanFailures()` parity. Sorted, deduped.
    /// Read from the published [`CachedSnapshot`] generation (one short
    /// lock); a cold index (nothing published) has no failures yet.
    ///
    /// COHERENCE NOTE: this standalone accessor is a point-in-time read of
    /// the CURRENT generation. A consumer that needs the snapshot AND its
    /// failures to come from the SAME generation (the resolve route) must
    /// use [`Self::snapshot_with_failures`] instead of pairing `snapshot()`
    /// with a later `scan_failures()` call.
    ///
    /// NODE PARITY NOTE: a throwing `listSessionFiles()` records a provider
    /// failure and preserves that provider's last-known-good file cache;
    /// healthy providers still prune their own deleted files
    /// (`session-indexer.ts:1512-1545`). The route merges the failure into
    /// `providerErrors` and marks the response `degraded` — never a silent
    /// healthy `ready + matches: []`. Both direct-listed (opencode) and
    /// file-backed (claude/codex/amplifier) outages are therefore recorded.
    pub fn scan_failures(&self) -> Vec<String> {
        let guard = self.snapshot.lock().unwrap();
        guard
            .as_ref()
            .map(|c| sorted_names(&c.scan_failures))
            .unwrap_or_default()
    }

    /// Fire-and-forget refresh (`requestRefresh` parity): gives a degraded
    /// response's Retry a chance to converge once a failed provider recovers.
    /// No-op if a sweep is already running.
    pub fn request_refresh(&self) {
        if let Ok(guard) = Arc::clone(&self.refresh_lock).try_lock_owned() {
            self.spawn_background_refresh(guard);
        }
    }

    /// Test-only arming for the D5-1 tail seam ([`PERFORM_REFRESH_TAIL_HOOK`]):
    /// installs the one-shot pause keyed to THIS index's `wake_pending`
    /// allocation (the only key `perform_refresh`'s tail will match), and
    /// returns the receiver the sweep signals once parked plus the sender
    /// that releases it.
    #[cfg(test)]
    fn install_refresh_tail_hook_for_test(
        &self,
    ) -> (
        tokio::sync::oneshot::Receiver<()>,
        tokio::sync::oneshot::Sender<()>,
    ) {
        let (parked_tx, parked_rx) = tokio::sync::oneshot::channel();
        let (resume_tx, resume_rx) = tokio::sync::oneshot::channel();
        *PERFORM_REFRESH_TAIL_HOOK.lock().unwrap() = Some((
            Arc::as_ptr(&self.wake_pending) as usize,
            parked_tx,
            resume_rx,
        ));
        (parked_rx, resume_tx)
    }

    /// Mark specific file paths as dirty. The next `snapshot()` call will
    /// re-stat these paths (and re-parse any that actually changed) even
    /// if the TTL hasn't expired. Paths not tracked by any source are
    /// harmlessly ignored during the refresh.
    pub fn mark_dirty(&self, paths: &[(PathBuf, String)]) {
        if paths.is_empty() {
            return;
        }
        {
            let mut dirty = self.dirty_paths.lock().unwrap();
            for (path, provider) in paths {
                dirty.insert(path.clone(), provider.clone());
            }
        }
        // D5-1: raise the wake flag after enqueuing and strictly BEFORE the
        // try-lock inside `request_refresh` (unconditionally — a store
        // ordered only after a FAILED try-lock is not causally fenced
        // against the sweeper's end-of-work consult; see `perform_refresh`).
        self.wake_pending.store(true, Ordering::SeqCst);
        self.request_refresh();
    }

    /// Mark an entire provider as dirty (e.g. its root directory appeared
    /// or disappeared). The next refresh runs a full `discover()` for
    /// that provider rather than only re-stat'ing individual dirty paths.
    pub fn mark_provider_dirty(&self, provider: &str) {
        {
            let mut dirty = self.dirty_providers.lock().unwrap();
            dirty.insert(provider.to_string());
        }
        // Same wake-flag ordering as `mark_dirty` (see it and
        // `perform_refresh`): flag strictly before the try-lock attempt.
        self.wake_pending.store(true, Ordering::SeqCst);
        self.request_refresh();
    }

    /// Register the self-correction report sink (amplifier watch-reduction
    /// design, "Self-correction channel"). After every sweep that fully
    /// discovers amplifier, the index sends the content-verified root
    /// session dirs (parsed metadata with `parent_id` absent) on this
    /// channel so the session watcher can arm any the name classifier
    /// missed. Best-effort: a dropped receiver just means no watcher is
    /// listening; the sends never block or fail the sweep.
    pub fn set_amplifier_root_report_sink(
        &self,
        sink: tokio::sync::mpsc::UnboundedSender<Vec<PathBuf>>,
    ) {
        *self.amplifier_root_report.lock().unwrap() = Some(sink);
    }

    /// Install the cold-start publish gate (amplifier watch-reduction Task
    /// 9's startup watcher-ready barrier). Boot-time, install-once, fed by
    /// `SessionWatcher::startup_ready()`: while a gate is installed AND no
    /// snapshot has ever been published, the two publish entries
    /// (`run_refresh_inline` and the spawned task inside
    /// `spawn_background_refresh`) await readiness BEFORE sweeping, so every
    /// boot-time snapshot caller (the warm spawn, the sessions sweep's
    /// initial signature snapshot, the auto-title first pass, pre-readiness
    /// request routes, mark-driven background refreshes — all of which
    /// funnel through exactly those two entries) publishes its FIRST
    /// generation provably after the watcher's startup arm pass settled.
    /// No watcher ⇒ no gate installed ⇒ today's exact behavior.
    pub fn set_startup_gate(&self, ready: tokio::sync::watch::Receiver<bool>) {
        *self.startup_gate.lock().unwrap() = Some(ready);
    }

    /// The cold-only startup-gate consult shared by both publish entries:
    /// while a gate is installed AND no snapshot has ever been published,
    /// await watcher readiness before sweeping — fail-OPEN on sender drop
    /// (`wait_for` errors when every sender is gone; a crashed watcher task
    /// must never wedge session serving). After the first publish the
    /// consult degenerates to a one-lock `is_some` no-op, so steady-state
    /// request/sweep paths pay nothing. Holding the refresh lock across the
    /// wait is deadlock-free: the readiness send happens in the watch loop,
    /// whose only index touches reach `request_refresh`'s non-blocking
    /// `try_lock`.
    async fn await_startup_gate(
        startup_gate: &StdMutex<Option<tokio::sync::watch::Receiver<bool>>>,
        snapshot: &StdMutex<Option<CachedSnapshot>>,
    ) {
        let gate = startup_gate.lock().unwrap().clone();
        let Some(mut gate) = gate else {
            return;
        };
        if snapshot.lock().unwrap().is_some() {
            return; // already published: steady-state no-op
        }
        let _ = gate.wait_for(|done| *done).await;
    }

    /// Subscribe to snapshot-change notifications. The receiver's value
    /// is a monotonic generation counter bumped every time a refresh
    /// publishes a snapshot with different content. Use
    /// `receiver.changed().await` to wake on the next real change.
    pub fn subscribe_changes(&self) -> tokio::sync::watch::Receiver<u64> {
        self.change_rx.clone()
    }

    /// Whether any dirty paths or providers are pending.
    pub fn has_dirty(&self) -> bool {
        has_dirty_parts(&self.dirty_paths, &self.dirty_providers)
    }

    /// Return a snapshot, pre-sorted `lastActivityAt` DESC then `key()` DESC
    /// (`projection.ts:51-62`'s comparator, applied once here instead of
    /// once per request).
    ///
    /// Stale-while-revalidate ("snapshot-swap"): if the cache is stale but a
    /// PREVIOUS snapshot exists, that snapshot is returned IMMEDIATELY and a
    /// fresh sweep runs detached in the background (see
    /// `spawn_background_refresh`) — this call never blocks on it. Only a
    /// truly cold cache (nothing ever published) waits for the sweep
    /// inline, via `run_refresh_inline`, since there is nothing else to
    /// serve. Either way, the actual rebuild is incremental (see
    /// [`refresh_snapshot`]), not a full re-parse of unchanged files.
    pub async fn snapshot(&self) -> Arc<Vec<IndexedSession>> {
        self.snapshot_with_failures().await.0
    }

    /// [`Self::snapshot`] plus the scan failures of the SAME published
    /// generation, read under ONE lock acquisition — the coherent read model
    /// for consumers (the resolve route) that must never pair a failed-scan
    /// snapshot with a cleared failure set, or a recovered snapshot with
    /// stale failures. Same stale-while-revalidate semantics as
    /// [`Self::snapshot`].
    pub async fn snapshot_with_failures(&self) -> (Arc<Vec<IndexedSession>>, Vec<String>) {
        if let Some(pair) = self.cached_pair(true) {
            return pair;
        }
        // Stale or absent. Try to become this round's sweeper WITHOUT
        // blocking -- `try_lock_owned` never waits, so a caller that
        // already has something to serve is never delayed by another
        // in-flight sweep.
        match Arc::clone(&self.refresh_lock).try_lock_owned() {
            Ok(guard) => {
                if let Some(stale) = self.cached_pair(false) {
                    // Someone must read fresh data eventually, but not THIS
                    // caller, and not by blocking anyone else either.
                    self.spawn_background_refresh(guard);
                    return stale;
                }
                // Truly cold: nothing to serve, so wait for the (only) sweep.
                self.run_refresh_inline(guard).await
            }
            Err(_) => {
                // Another caller is already sweeping this round.
                if let Some(stale) = self.cached_pair(false) {
                    return stale;
                }
                // Truly cold AND racing another cold-start caller: wait for
                // THEIR sweep instead of starting a second one (preserves
                // B-T5's "N concurrent misses -> 1 sweep" guarantee for the
                // cold-cache case).
                let guard = self.refresh_lock.lock().await;
                let pair = self
                    .cached_pair(true)
                    .or_else(|| self.cached_pair(false))
                    .unwrap_or_default();
                drop(guard);
                // D5-1: this caller held `refresh_lock` (however briefly),
                // so any mark whose try-lock failed during that window
                // stored the wake flag beforehand and relies on a holder's
                // exit consult — the same consult every other guard release
                // performs (see `perform_refresh`'s tail). If the consult's
                // own try-lock fails, the then-current holder's exit consult
                // sees the same still-set flag.
                if self.wake_pending.load(Ordering::SeqCst) {
                    if let Ok(next) = Arc::clone(&self.refresh_lock).try_lock_owned() {
                        let _ = Self::perform_refresh(
                            next,
                            Arc::clone(&self.refresh_lock),
                            Arc::clone(&self.wake_pending),
                            self.sources.clone(),
                            Arc::clone(&self.file_cache),
                            Arc::clone(&self.direct_cache),
                            Arc::clone(&self.snapshot),
                            self.persist_path.clone(),
                            Arc::clone(&self.persist_state),
                            Arc::clone(&self.dirty_paths),
                            Arc::clone(&self.dirty_providers),
                            Arc::clone(&self.last_full_at),
                            self.ttl,
                            self.change_tx.clone(),
                            Arc::clone(&self.amplifier_root_report),
                        )
                        .await;
                    }
                }
                pair
            }
        }
    }

    /// Sync, non-blocking read of the last PUBLISHED snapshot — fresh or
    /// stale — or `None` when the cache is truly cold (nothing ever
    /// published). This is the reconciliation handshake's disk-truth read
    /// (`freshell-server`'s `SessionExistenceProbe` impl): a sync caller that
    /// must never wait on a sweep. `None` is what makes the probe's `Unknown`
    /// honest; pair with [`Self::is_fresh`] to decide whether to kick a
    /// background `snapshot()` refresh.
    pub fn peek(&self) -> Option<Arc<Vec<IndexedSession>>> {
        self.any_cached()
    }

    /// Whether the published snapshot (if any) is within the TTL window —
    /// the sync freshness companion to [`Self::peek`].
    pub fn is_fresh(&self) -> bool {
        self.fresh_cached().is_some()
    }

    /// The cached snapshot, if present and within the TTL window. A brief,
    /// non-async lock: never held across an await point.
    fn fresh_cached(&self) -> Option<Arc<Vec<IndexedSession>>> {
        self.cached_pair(true).map(|(items, _)| items)
    }

    /// The cached snapshot, if present, regardless of TTL freshness -- the
    /// stale-while-revalidate read: "is there ANYTHING to serve right now."
    fn any_cached(&self) -> Option<Arc<Vec<IndexedSession>>> {
        self.cached_pair(false).map(|(items, _)| items)
    }

    /// The cached `(snapshot, scan_failures)` pair of the SAME published
    /// generation, read under ONE lock acquisition (never held across an
    /// await point). `require_fresh` applies the TTL window; `false` is the
    /// stale-while-revalidate read.
    fn cached_pair(&self, require_fresh: bool) -> Option<(Arc<Vec<IndexedSession>>, Vec<String>)> {
        let guard = self.snapshot.lock().unwrap();
        match guard.as_ref() {
            Some(c) if !require_fresh || c.fetched_at.elapsed() < self.ttl => {
                if require_fresh && self.has_dirty() {
                    return None;
                }
                // Scoped refreshes keep fetched_at fresh, but a full
                // reconciliation may still be overdue. Force a refresh
                // when last_full_at exceeds the TTL so new provider
                // roots and deleted sessions are discovered.
                if require_fresh {
                    let last = self.last_full_at.lock().unwrap();
                    if last.is_none_or(|at| at.elapsed() >= self.ttl) {
                        return None;
                    }
                }
                Some((Arc::clone(&c.items), sorted_names(&c.scan_failures)))
            }
            _ => None,
        }
    }

    /// Cold-start path: run the sweep and wait for it (there is nothing else
    /// to serve). `guard` is held for the sweep's full duration -- exactly
    /// the pre-fix behavior, but now reachable ONLY when no snapshot has
    /// ever been published, never for a routine stale-cache refresh. The
    /// guard moves INTO `perform_refresh`, which owns the end-of-work
    /// quiescence handoff (release + wake-flag consult, delta D5-1).
    async fn run_refresh_inline(
        &self,
        guard: tokio::sync::OwnedMutexGuard<()>,
    ) -> (Arc<Vec<IndexedSession>>, Vec<String>) {
        // Task 9 cold-start publish gate: reachable ONLY cold (a published
        // snapshot short-circuits `snapshot_with_failures` before this
        // path), so the consult's own cold re-check is belt-and-braces.
        Self::await_startup_gate(&self.startup_gate, &self.snapshot).await;
        Self::perform_refresh(
            guard,
            Arc::clone(&self.refresh_lock),
            Arc::clone(&self.wake_pending),
            self.sources.clone(),
            Arc::clone(&self.file_cache),
            Arc::clone(&self.direct_cache),
            Arc::clone(&self.snapshot),
            self.persist_path.clone(),
            Arc::clone(&self.persist_state),
            Arc::clone(&self.dirty_paths),
            Arc::clone(&self.dirty_providers),
            Arc::clone(&self.last_full_at),
            self.ttl,
            self.change_tx.clone(),
            Arc::clone(&self.amplifier_root_report),
        )
        .await
    }

    /// Warm-cache path: run the sweep DETACHED, so the caller that triggered
    /// it (and every other concurrent caller) can go on serving the stale
    /// snapshot immediately. `guard` moves into the spawned task and —
    /// inside `perform_refresh`, which owns the end-of-work quiescence
    /// handoff (delta D5-1) — is released only once that sweep fully
    /// completes, so `try_lock_owned` correctly rejects any other concurrent
    /// sweeper until then.
    fn spawn_background_refresh(&self, guard: tokio::sync::OwnedMutexGuard<()>) {
        let refresh_lock = Arc::clone(&self.refresh_lock);
        let wake_pending = Arc::clone(&self.wake_pending);
        let sources = self.sources.clone();
        let file_cache = Arc::clone(&self.file_cache);
        let direct_cache = Arc::clone(&self.direct_cache);
        let snapshot = Arc::clone(&self.snapshot);
        let persist_path = self.persist_path.clone();
        let persist_state = Arc::clone(&self.persist_state);
        let dirty_paths = Arc::clone(&self.dirty_paths);
        let dirty_providers = Arc::clone(&self.dirty_providers);
        let last_full_at = Arc::clone(&self.last_full_at);
        let ttl = self.ttl;
        let change_tx = self.change_tx.clone();
        let amplifier_root_report = Arc::clone(&self.amplifier_root_report);
        let startup_gate = Arc::clone(&self.startup_gate);
        tokio::spawn(async move {
            // Task 9 cold-start publish gate: `request_refresh` (mark_dirty /
            // mark_provider_dirty — incl. the subagent cadence itself) reaches
            // this entry possibly-cold, so the consult MUST live here too —
            // and it is a one-lock no-op once anything has published, so the
            // steady-state stale-while-revalidate path never waits on it.
            Self::await_startup_gate(&startup_gate, &snapshot).await;
            let _ = Self::perform_refresh(
                guard,
                refresh_lock,
                wake_pending,
                sources,
                file_cache,
                direct_cache,
                snapshot,
                persist_path,
                persist_state,
                dirty_paths,
                dirty_providers,
                last_full_at,
                ttl,
                change_tx,
                amplifier_root_report,
            )
            .await;
        });
    }

    /// The actual sweep: discover/parse (incremental, off the async
    /// executor thread via `spawn_blocking`), publish the result into
    /// `snapshot`, then opportunistically persist the parse cache. Free of
    /// any `&SessionIndex` borrow -- every input is an owned `Arc`/value --
    /// so it runs identically whether awaited inline (cold start) or inside
    /// a detached `tokio::spawn` (warm, stale-while-revalidate refresh).
    ///
    /// Delta D4-2 (the lost-wakeup race, mid-sweep form): `mark_dirty` /
    /// `mark_provider_dirty` attempt `request_refresh` ONCE; a refresh
    /// already in flight holds `refresh_lock`, so that attempt is DROPPED —
    /// and a sweep drains the dirty maps at its START, so a mark landing
    /// MID-sweep would otherwise sit until some unrelated caller happened
    /// to refresh again (the pre-watch-reduction handling serviced such
    /// marks sub-second). After each sweep, re-check the dirty state: if
    /// any mark arrived while it ran, run ONE follow-up sweep, looping
    /// until the re-check comes back empty ("quiescent").
    ///
    /// Delta D5-1 (the lost-wakeup race, check-to-unlock form): the D4-2
    /// re-check alone leaves a terminal window — a mark landing AFTER the
    /// final re-check yet BEFORE the guard release failed its one try-lock
    /// (the guard was still held) and was never serviced. The close-out is
    /// a wake-flag handshake with `wake_pending`, with the orderings that
    /// exclude every interleaving — NO MARK IS EVER LOST:
    ///
    /// * Markers ALWAYS store `wake_pending = true` after enqueueing and
    ///   BEFORE attempting the try-lock (unconditionally: a store ordered
    ///   only behind a FAILED try-lock would not be causally fenced against
    ///   the sweeper's end-of-work consult — preemption between the failed
    ///   try-lock and the store would re-open the hole).
    /// * Every sweep iteration begins by ABSORBING the flag (store
    ///   `false`). The iteration's drain runs later in program order, so
    ///   every mark whose store preceded the absorb has its enqueue ordered
    ///   before that drain and is covered by it — an absorb can therefore
    ///   never orphan a mark.
    /// * The sweeper's end-of-work consult happens strictly AFTER the guard
    ///   release. A mark whose try-lock failed against THIS guard stored
    ///   the flag beforehand, and the failed try-lock precedes the release
    ///   (a try-lock fails only while the guard is held), so the
    ///   post-release consult provably runs after the store: it reads the
    ///   flag set, re-acquires the guard, and loops — the next iteration's
    ///   absorb + drain services the mark. If the consult's try-lock fails,
    ///   another holder exists, and every guard release performs the same
    ///   consult on the still-set flag — unless some sweep iteration's
    ///   absorb already consumed it, in which case that iteration's paired
    ///   drain covered the mark.
    ///
    /// The refresh_lock guard moves INTO this call (from `run_refresh_inline`,
    /// `spawn_background_refresh`, or the cold-cache awaiter): the release
    /// and the wake-flag consult are the end-of-work path of the sweep
    /// itself. The loop is bounded exactly as in D4-2 — it continues only
    /// on a non-empty dirty re-check or a set wake flag, both driven by
    /// real marks (already debounce-bounded by the watcher's 200ms flush);
    /// a set flag over quiesced dirty maps costs exactly one empty pass and
    /// leaves the flag clear.
    #[allow(clippy::too_many_arguments)]
    async fn perform_refresh(
        guard: tokio::sync::OwnedMutexGuard<()>,
        refresh_lock: Arc<AsyncMutex<()>>,
        wake_pending: Arc<AtomicBool>,
        sources: Vec<Arc<dyn SessionSource>>,
        file_cache: Arc<StdMutex<HashMap<PathBuf, FileEntry>>>,
        direct_cache: Arc<StdMutex<HashMap<usize, DirectEntry>>>,
        snapshot: Arc<StdMutex<Option<CachedSnapshot>>>,
        persist_path: Option<PathBuf>,
        persist_state: Arc<StdMutex<PersistState>>,
        dirty_paths: Arc<StdMutex<HashMap<PathBuf, String>>>,
        dirty_providers: Arc<StdMutex<HashSet<String>>>,
        last_full_at: Arc<StdMutex<Option<Instant>>>,
        ttl: Duration,
        change_tx: tokio::sync::watch::Sender<u64>,
        amplifier_root_report: Arc<
            StdMutex<Option<tokio::sync::mpsc::UnboundedSender<Vec<PathBuf>>>>,
        >,
    ) -> (Arc<Vec<IndexedSession>>, Vec<String>) {
        let mut guard = guard;
        loop {
            // Absorb the wake flag at iteration start; this iteration's
            // drain (inside `perform_refresh_once`) is ordered after the
            // absorb, and every mark whose store preceded the absorb has
            // its enqueue ordered before that drain.
            wake_pending.store(false, Ordering::SeqCst);
            let pair = Self::perform_refresh_once(
                sources.clone(),
                Arc::clone(&file_cache),
                Arc::clone(&direct_cache),
                Arc::clone(&snapshot),
                persist_path.clone(),
                Arc::clone(&persist_state),
                Arc::clone(&dirty_paths),
                Arc::clone(&dirty_providers),
                Arc::clone(&last_full_at),
                ttl,
                change_tx.clone(),
                Arc::clone(&amplifier_root_report),
            )
            .await;
            // D4-2: a mark that landed MID-sweep is picked up by exactly one
            // follow-up iteration; loop until the re-check comes back empty.
            if has_dirty_parts(&dirty_paths, &dirty_providers) {
                continue;
            }
            #[cfg(test)]
            {
                let hook = {
                    let key = Arc::as_ptr(&wake_pending) as usize;
                    let mut slot = PERFORM_REFRESH_TAIL_HOOK.lock().unwrap();
                    match slot.as_ref() {
                        Some((armed_for, _, _)) if *armed_for == key => slot.take(),
                        _ => None,
                    }
                };
                if let Some((_, parked, resume)) = hook {
                    let _ = parked.send(());
                    let _ = resume.await;
                }
            }
            drop(guard);
            // D5-1: the final dirty re-check ran BEFORE the guard release
            // above, so a mark landing in the check-to-unlock window failed
            // its try-lock against this guard — and stored the wake flag
            // before that try-lock, hence provably before this consult. A
            // set flag means: re-acquire and run one more iteration (its
            // absorb + drain services the mark); a clean flag means real
            // quiescence.
            if !wake_pending.load(Ordering::SeqCst) {
                return pair;
            }
            guard = match Arc::clone(&refresh_lock).try_lock_owned() {
                Ok(next) => next,
                // Another holder sweep exists; its own end-of-work consult
                // reads the same still-set flag (or an iteration absorb
                // consumed it, pairing the flag with that iteration's
                // drain — either way the mark is covered).
                Err(_) => return pair,
            };
        }
    }

    /// One full sweep of [`Self::perform_refresh`]'s refresh cycle (drain
    /// the dirty maps, discover/parse, publish, persist). Split out so the
    /// quiescence loop above can re-run it for mid-sweep marks; callers
    /// never invoke it directly.
    #[allow(clippy::too_many_arguments)]
    async fn perform_refresh_once(
        sources: Vec<Arc<dyn SessionSource>>,
        file_cache: Arc<StdMutex<HashMap<PathBuf, FileEntry>>>,
        direct_cache: Arc<StdMutex<HashMap<usize, DirectEntry>>>,
        snapshot: Arc<StdMutex<Option<CachedSnapshot>>>,
        persist_path: Option<PathBuf>,
        persist_state: Arc<StdMutex<PersistState>>,
        dirty_paths: Arc<StdMutex<HashMap<PathBuf, String>>>,
        dirty_providers: Arc<StdMutex<HashSet<String>>>,
        last_full_at: Arc<StdMutex<Option<Instant>>>,
        ttl: Duration,
        change_tx: tokio::sync::watch::Sender<u64>,
        amplifier_root_report: Arc<
            StdMutex<Option<tokio::sync::mpsc::UnboundedSender<Vec<PathBuf>>>>,
        >,
    ) -> (Arc<Vec<IndexedSession>>, Vec<String>) {
        // Force a full reconciliation when:
        // - no snapshot has been published yet (cold start), or
        // - the TTL has elapsed since the last full reconciliation
        let force_full = {
            let snapshot_exists = snapshot.lock().unwrap().is_some();
            let last = *last_full_at.lock().unwrap();
            !snapshot_exists || last.is_none_or(|at| at.elapsed() >= ttl)
        };

        let sweep_result = tokio::task::spawn_blocking({
            let file_cache = Arc::clone(&file_cache);
            let direct_cache = Arc::clone(&direct_cache);
            let snapshot = Arc::clone(&snapshot);
            move || {
                let (scoped_paths, scoped_providers) = if force_full {
                    dirty_paths.lock().unwrap().clear();
                    dirty_providers.lock().unwrap().clear();
                    (HashMap::new(), HashSet::new())
                } else {
                    let sp: HashMap<PathBuf, String> =
                        dirty_paths.lock().unwrap().drain().collect();
                    let sprov: HashSet<String> = dirty_providers.lock().unwrap().drain().collect();
                    (sp, sprov)
                };
                let mut cache = file_cache.lock().unwrap();
                let mut direct = direct_cache.lock().unwrap();
                // Seed the failure set from the last PUBLISHED generation in
                // a SHORT lock and mutate the LOCAL copy during the sweep —
                // `scan_failures()`/`cached_pair()` are sync accessors
                // called from async route handlers right after a
                // stale-while-revalidate `snapshot()`, so holding the
                // snapshot mutex across a multi-second sweep would block a
                // runtime thread exactly when degraded responses are being
                // served. The updated set is published below IN THE SAME
                // lock write as the new snapshot (one atomic generation).
                // Lost updates are impossible: `refresh_lock` guarantees at
                // most one sweep at a time.
                let mut failures = snapshot
                    .lock()
                    .unwrap()
                    .as_ref()
                    .map(|c| c.scan_failures.clone())
                    .unwrap_or_default();
                let (items, changed, amplifier_root_dirs) = refresh_snapshot(
                    &sources,
                    &mut cache,
                    &mut direct,
                    &mut failures,
                    scoped_paths,
                    scoped_providers,
                );
                (items, changed, failures, amplifier_root_dirs)
            }
        })
        .await;
        let (items, changed, failures, amplifier_root_dirs) = match sweep_result {
            Ok(result) => result,
            Err(join_err) => {
                // `discover`/`parse` are documented never-panic (every
                // `SessionSource` impl is corruption-tolerant), so this is
                // currently unreachable -- but IF that invariant is ever
                // violated, publishing `(vec![], 0)` here (the old
                // `unwrap_or_default()` behavior) would silently overwrite a
                // good, previously-published snapshot with an empty one
                // marked FRESH. Preserve whatever's already published
                // instead (items AND failures — the whole generation),
                // mirroring `refresh_snapshot`'s own `direct_list`-error
                // handling a few lines above (preserve-cached + log) rather
                // than dropping data.
                eprintln!(
                    "session-directory: refresh sweep panicked (preserving cached \
                     snapshot): {join_err}"
                );
                return snapshot
                    .lock()
                    .unwrap()
                    .as_ref()
                    .map(|c| (Arc::clone(&c.items), sorted_names(&c.scan_failures)))
                    .unwrap_or_default();
            }
        };
        let items = Arc::new(items);
        let failure_names = sorted_names(&failures);
        {
            // ONE lock write publishes the snapshot AND its scan failures as
            // a single generation — a reader (`cached_pair`) can never
            // observe a failed-scan snapshot paired with a cleared failure
            // set, nor a recovered snapshot paired with stale failures.
            let mut guard = snapshot.lock().unwrap();
            *guard = Some(CachedSnapshot {
                items: Arc::clone(&items),
                fetched_at: Instant::now(),
                scan_failures: failures,
            });
        } // guard dropped here — never held across an .await.
          // Self-correction report (amplifier watch-reduction design
          // "Self-correction channel"): sent only on sweeps that fully
          // discovered amplifier (`refresh_snapshot` computes `None`
          // otherwise), immediately after the snapshot publish. One-way,
          // best-effort: a dropped receiver means no watcher is listening.
        if let Some(dirs) = amplifier_root_dirs {
            if let Some(sink) = amplifier_root_report.lock().unwrap().as_ref() {
                let _ = sink.send(dirs);
            }
        }
        if force_full {
            *last_full_at.lock().unwrap() = Some(Instant::now());
        }
        if changed > 0 {
            change_tx.send_modify(|gen| *gen += 1);
        }
        // Opportunistic persistence: gated (threshold/debounce) and, when
        // warranted, saved via a DETACHED task -- never awaited here, so
        // neither an HTTP request handler NOR this refresh itself is
        // delayed by a disk write.
        if let Some((path, cache_snapshot)) = take_pending_save_from_parts(
            &persist_path,
            &persist_state,
            &file_cache,
            changed,
            SAVE_DEBOUNCE,
        ) {
            tokio::spawn(async move {
                let outcome =
                    tokio::task::spawn_blocking(move || save_cache_file(&path, &cache_snapshot))
                        .await;
                match outcome {
                    Ok(Ok(())) => {}
                    Ok(Err(err)) => {
                        eprintln!("session-directory: failed to persist parse cache: {err}")
                    }
                    Err(join_err) => {
                        eprintln!("session-directory: persist task panicked: {join_err}")
                    }
                }
            });
        }
        (items, failure_names)
    }

    /// Populate the cache once, eagerly. Call from `main.rs` via
    /// `tokio::spawn` at boot so the first real request never pays the cold
    /// full-sweep cost — cheap for a small home, and the sweep already runs
    /// off the executor thread, so it never delays serving other requests.
    pub async fn warm(&self) {
        let _ = self.snapshot().await;
    }
}

/// Free-function form of the save-decision gate (see
/// `SessionIndex::take_pending_save_with_debounce`'s doc comment for the
/// full rule) -- takes its inputs by reference instead of `&self` so a
/// detached background-refresh task (which owns `Arc`s, not a
/// `&SessionIndex`) can call it directly. Rule: a save is warranted iff at
/// least one cache entry changed since the last save AND (this is the very
/// first-ever sweep, OR the cumulative changed-since-save count has reached
/// `SAVE_CHANGED_THRESHOLD`, OR the debounce window has elapsed since the
/// last save). On a "yes", resets the changed-since-save counter and
/// returns a cloned snapshot of the file cache to write (cloned while still
/// holding the state lock, so two concurrent sweeps can never both decide
/// "yes" for the same window).
fn take_pending_save_from_parts(
    persist_path: &Option<PathBuf>,
    persist_state: &StdMutex<PersistState>,
    file_cache: &StdMutex<HashMap<PathBuf, FileEntry>>,
    changed_this_sweep: usize,
    debounce: Duration,
) -> Option<(PathBuf, HashMap<PathBuf, FileEntry>)> {
    let path = persist_path.clone()?;
    let mut state = persist_state.lock().unwrap();
    state.changed_since_save = state
        .changed_since_save
        .saturating_add(changed_this_sweep as u64);
    if state.changed_since_save == 0 {
        return None;
    }
    let should_save = !state.saved_once
        || state.changed_since_save >= SAVE_CHANGED_THRESHOLD
        || state.last_saved_at.is_none_or(|t| t.elapsed() >= debounce);
    if !should_save {
        return None;
    }
    state.changed_since_save = 0;
    state.last_saved_at = Some(Instant::now());
    state.saved_once = true;
    drop(state);
    let cache_snapshot = file_cache.lock().unwrap().clone();
    Some((path, cache_snapshot))
}

/// Sorted, deduped provider names from a scan-failure set — the wire shape
/// [`SessionIndex::scan_failures`]/[`SessionIndex::snapshot_with_failures`]
/// expose (`getScanFailures` parity: stable order for assertions/dedupe).
fn sorted_names(failures: &HashSet<String>) -> Vec<String> {
    let mut names: Vec<String> = failures.iter().cloned().collect();
    names.sort();
    names
}

/// Test-only seam for the D5-1 regression test (see `mod tests`): a
/// one-shot pause INSIDE [`SessionIndex::perform_refresh`]'s tail — after
/// the final quiescence re-check has reported clean and BEFORE the sweep's
/// `refresh_lock` guard is released — so a test can land a dirty mark
/// strictly inside the check-to-unlock window, deterministically. Never
/// armed in production (`cfg(test)`-only, and only ever constructed by the
/// one test that installs it). The hook is keyed by the identity of the
/// arming index's `wake_pending` allocation, so a CONCURRENT test's sweep
/// (which reaches the same tail code under the shared test binary) can
/// never consume it: only a sweep of the arming test's own index matches
/// and takes. `take()` makes it fire exactly once, and a panicking test
/// can never leak an armed hook that a later test would match (a new index
/// is a new allocation).
#[cfg(test)]
#[allow(clippy::type_complexity)]
static PERFORM_REFRESH_TAIL_HOOK: StdMutex<
    Option<(
        usize,
        tokio::sync::oneshot::Sender<()>,
        tokio::sync::oneshot::Receiver<()>,
    )>,
> = StdMutex::new(None);

/// The dirty-state re-check shape shared by [`SessionIndex::has_dirty`]
/// (the public probe) and [`SessionIndex::perform_refresh`]'s sweep-end
/// re-check (delta D4-2): true iff any scoped path or whole provider is
/// marked pending. ONE locked section consulting BOTH maps (paths before
/// providers — the only nested acquisition of these two locks anywhere;
/// markers lock exactly one map each and the sweep's drain takes them one
/// at a time, so no lock cycle is possible), never held across an await
/// point. The atomicity matters (delta D5-1): a quiescence decision must
/// observe both maps at a single point — a scoped-path mark and a
/// whole-provider mark landing on opposite sides of two independent reads
/// could otherwise straddle the sweeper's final check.
fn has_dirty_parts(
    dirty_paths: &StdMutex<HashMap<PathBuf, String>>,
    dirty_providers: &StdMutex<HashSet<String>>,
) -> bool {
    let paths = dirty_paths.lock().unwrap();
    let providers = dirty_providers.lock().unwrap();
    !paths.is_empty() || !providers.is_empty()
}

/// One cached direct-listed source's last successful listing, keyed by
/// source index in [`SessionIndex::direct_cache`]. Mirrors [`FileEntry`]'s
/// role for file-based sources, but keyed by change-token instead of
/// `(mtime, size)`, and holding a full `Vec` of sessions instead of one.
struct DirectEntry {
    token: i64,
    items: Vec<IndexedSession>,
}

/// Parse a scoped dirty path by finding the right source. Prefers the
/// Parse a single dirty path using the provider hint from the watcher.
/// The hint is authoritative — the watcher knows which provider's watch
/// base produced the event, so trying other parsers would misclassify
/// files (e.g. a Codex `.jsonl` parsed as Claude). Falls back to trying
/// each file-backed source only when no hint is available (cold cache
/// migration). Returns `(item, source_name)` where `item` is `None` for
/// an exclusion (e.g. R10b cwd-less rule).
fn parse_scoped_path(
    path: &Path,
    sources: &[Arc<dyn SessionSource>],
    provider_hint: Option<&str>,
) -> (Option<IndexedSession>, Option<String>) {
    if let Some(name) = provider_hint {
        if let Some(source) = sources.iter().find(|s| s.provider_name() == Some(name)) {
            return (source.parse(path), Some(name.to_owned()));
        }
    }
    for source in sources {
        if source.direct_change_token().is_some() {
            continue;
        }
        if let Some(item) = source.parse(path) {
            return (Some(item), source.provider_name().map(str::to_owned));
        }
    }
    (None, None)
}

/// One incremental refresh sweep across all sources:
///
/// 1. File-based sources: `discover()` the current `(path, mtime, size)` set
///    — stat only, no parsing. Re-`parse()` ONLY a file that's new or whose
///    `mtime`/`size` changed since the cached [`FileEntry`]; reuse the cached
///    entry (including a cached EXCLUSION, `item: None`) for everything
///    else. A re-parse counts toward the sweep's `changed` total ONLY when
///    the re-parsed item actually differs from the cached one — a
///    content-identical rewrite (same bytes, only mtime/size moved) is pure
///    stat-bookkeeping and must never advance the change generation. Prune
///    `cache` entries for paths no longer discovered (deleted files).
/// 2. Direct-listed sources (Batch C: opencode): call
///    [`SessionSource::direct_change_token`] — cheap, no query. If the token
///    matches the cached [`DirectEntry`], reuse its `items` unchanged. If it
///    changed (or there's no cached entry yet), call
///    [`SessionSource::direct_list`]: `Ok` replaces the cache entry, `Err`
///    logs once and leaves whatever was cached (never drops that provider's
///    sessions from the snapshot over a transient read failure).
/// 3. Rebuild + re-sort the combined snapshot from both caches — the ONE
///    sort per sweep (not once per request), over already-parsed/listed
///    data, no disk I/O beyond what steps 1-2 already did.
///
/// A sweep over N unchanged files costs N stats, not N parses — this is what
/// fixes the "5s problem returns after 1s TTL" regression the FIRST shipped
/// version of this module had (see the module doc comment). Analogously, a
/// sweep over an unchanged direct-listed source costs 2 stats (db + db-wal),
/// not a query.
fn refresh_snapshot(
    sources: &[Arc<dyn SessionSource>],
    cache: &mut HashMap<PathBuf, FileEntry>,
    direct_cache: &mut HashMap<usize, DirectEntry>,
    scan_failures: &mut HashSet<String>,
    scoped_paths: HashMap<PathBuf, String>,
    scoped_providers: HashSet<String>,
) -> (Vec<IndexedSession>, usize, Option<Vec<PathBuf>>) {
    let is_full = scoped_paths.is_empty() && scoped_providers.is_empty();
    let mut discovered: std::collections::HashSet<PathBuf> = std::collections::HashSet::new();
    let mut fully_discovered_providers = HashSet::<String>::new();
    // A failed root listing cannot distinguish "everything disappeared" from
    // "this provider is temporarily unreadable." Remember failures by source
    // so their rows stay cached while healthy providers still reconcile real
    // deletions. Legacy cache entries without a source marker are retained
    // conservatively during any failed sweep until a healthy scan marks them.
    let mut file_backed_discovery_failed = false;
    let mut failed_file_source_names = HashSet::<String>::new();
    // Count of file-cache mutations + direct-listed sources re-queried this
    // sweep -- the persistent-parse-cache save gate's "how much changed"
    // signal (`SessionIndex::take_pending_save`). Stats-only unchanged
    // files/tokens don't count.
    let mut changed = 0usize;
    for (idx, source) in sources.iter().enumerate() {
        if let Some(token) = source.direct_change_token() {
            let provider_dirty = source
                .provider_name()
                .is_some_and(|n| scoped_providers.contains(n));
            let unchanged =
                !provider_dirty && direct_cache.get(&idx).is_some_and(|e| e.token == token);
            if unchanged {
                // HEALTH evidence must be refreshed EVERY sweep (Node parity:
                // `refreshDirectProvider()` runs on every full scan and
                // records/clears `scanFailures` per attempt,
                // `session-indexer.ts:1457`, `:1070-1082`). The unchanged
                // mtime token gates only the expensive re-QUERY of session
                // DATA -- a database can become locked or unreadable (e.g.
                // `chmod`) without either watched mtime moving, so reporting
                // `ready` from the stale cache here would violate the "never
                // present unsearchable as healthy" contract.
                match source.direct_health_check() {
                    Ok(()) => {
                        if let Some(name) = source.provider_name() {
                            scan_failures.remove(name);
                        }
                    }
                    Err(err) => {
                        if let Some(name) = source.provider_name() {
                            scan_failures.insert(name.to_string());
                        }
                        eprintln!(
                            "session-directory: direct-listed source #{idx} health check \
                             failed (preserving cached sessions): {err}"
                        );
                    }
                }
            } else {
                match source.direct_list() {
                    Ok(items) => {
                        if let Some(name) = source.provider_name() {
                            scan_failures.remove(name);
                        }
                        direct_cache.insert(idx, DirectEntry { token, items });
                        changed += 1;
                    }
                    Err(err) => {
                        // Record the outage (`getScanFailures` parity) so the
                        // resolve route can surface it as a degraded
                        // providerError instead of a silent healthy empty.
                        if let Some(name) = source.provider_name() {
                            scan_failures.insert(name.to_string());
                        }
                        // Preserve whatever was cached from the last
                        // successful listing (e.g. a locked/mid-write
                        // sqlite db) -- never drop this provider's sessions
                        // from the snapshot over a transient read error.
                        eprintln!(
                            "session-directory: direct-listed source #{idx} read error \
                             (preserving cached sessions): {err}"
                        );
                    }
                }
            }
            // Direct-listed sources never touch the per-file cache/discovery.
            continue;
        }

        // File-backed: skip full discover when a scoped refresh covers
        // only specific paths (not this provider). Full reconciliation
        // and provider-level dirty marks do the full discover.
        let source_name = source.provider_name().map(str::to_owned);
        let should_discover = is_full
            || source_name
                .as_deref()
                .is_some_and(|n| scoped_providers.contains(n));
        if !should_discover {
            continue;
        }
        if let Some(ref name) = source_name {
            fully_discovered_providers.insert(name.clone());
        }
        // A ROOT-listing failure is recorded and preserves the existing
        // cache. Treating it as an empty listing makes a transient
        // permission/I/O outage look like mass deletion and can persist a
        // gutted cache for the next boot.
        let stats = match source.discover_checked() {
            Ok(stats) => {
                if let Some(name) = source.provider_name() {
                    scan_failures.remove(name);
                }
                stats
            }
            Err(err) => {
                file_backed_discovery_failed = true;
                if let Some(name) = source.provider_name() {
                    scan_failures.insert(name.to_string());
                    failed_file_source_names.insert(name.to_string());
                }
                eprintln!(
                    "session-directory: source #{idx} root listing failed \
                     (preserving file cache this sweep): {err}"
                );
                Vec::new()
            }
        };
        for stat in stats {
            let unchanged = cache
                .get(&stat.path)
                .is_some_and(|entry| entry.mtime_ms == stat.mtime_ms && entry.size == stat.size);
            if unchanged {
                // Migrate older persisted entries (and correct any stale
                // ownership) without reparsing an otherwise unchanged file.
                if cache
                    .get(&stat.path)
                    .is_some_and(|entry| entry.source_name != source_name)
                {
                    if let Some(entry) = cache.get_mut(&stat.path) {
                        entry.source_name = source_name.clone();
                        changed += 1;
                    }
                }
            } else {
                let item = source.parse(&stat.path);
                // A content-IDENTICAL rewrite (editor autosave, a repeated
                // provider write: same bytes, only mtime/size moved)
                // re-parses to exactly the cached item. Count ONLY a re-parse
                // whose parsed view (or ownership) actually differs as a
                // change — a phantom cache mutation would advance the change
                // generation, which since 6af41f272's unconditional wake-arm
                // broadcast fans a spurious `sessions.changed` out to every
                // client. The stat bookkeeping (mtime_ms/size) is refreshed
                // either way so the NEXT sweep treats the file as unchanged.
                let content_moved = cache
                    .get(&stat.path)
                    .is_none_or(|entry| entry.item != item || entry.source_name != source_name);
                cache.insert(
                    stat.path.clone(),
                    FileEntry {
                        source_name: source_name.clone(),
                        mtime_ms: stat.mtime_ms,
                        size: stat.size,
                        item,
                    },
                );
                if content_moved {
                    changed += 1;
                }
            }
            discovered.insert(stat.path);
        }
    }

    // Scoped-path handling: stat + conditionally re-parse individual
    // dirty paths that weren't already covered by a provider-level
    // discover above. These paths came from the watcher (already
    // qualified), so we only need to re-stat and re-parse on change. The
    // re-stat goes through the hinted source's `stat_scoped` so the cache
    // key written here matches the discover path's key exactly (amplifier
    // folds sidecar mtimes on both; a no-hint path keeps the raw stat).
    if !is_full {
        for (path, watcher_provider) in &scoped_paths {
            if discovered.contains(path) {
                continue;
            }
            let hinted = sources
                .iter()
                .find(|s| s.provider_name() == Some(watcher_provider.as_str()));
            match hinted
                .map(|s| s.stat_scoped(path))
                .unwrap_or_else(|| stat_file(path))
            {
                Some(stat) => {
                    discovered.insert(path.clone());
                    let unchanged = cache
                        .get(path)
                        .is_some_and(|e| e.mtime_ms == stat.mtime_ms && e.size == stat.size);
                    if !unchanged {
                        let (item, resolved_source) =
                            parse_scoped_path(path, sources, Some(watcher_provider));
                        // Same content-identical-rewrite rule as the discover
                        // arm above: a watcher-scoped re-parse whose parsed
                        // view matches the cached item is bookkeeping, not a
                        // change — else it bumps the generation and wakes a
                        // spurious `sessions.changed` broadcast.
                        let content_moved = cache.get(path).is_none_or(|entry| {
                            entry.item != item || entry.source_name != resolved_source
                        });
                        cache.insert(
                            path.clone(),
                            FileEntry {
                                source_name: resolved_source,
                                mtime_ms: stat.mtime_ms,
                                size: stat.size,
                                item,
                            },
                        );
                        if content_moved {
                            changed += 1;
                        }
                    }
                }
                None => {
                    if cache.remove(path).is_some() {
                        changed += 1;
                    }
                }
            }
        }
    }

    // Self-correction report (refresh → watcher, one-way; amplifier
    // watch-reduction design "Self-correction channel"): a sweep that
    // fully discovered amplifier reports every amplifier session dir
    // whose PARSED metadata proves a root (`parent_id` absent ⇔
    // `!is_subagent`). The dirs come from the file-cache KEYS (canonical
    // metadata.json paths → parent dir) — amplifier rows publish
    // `source_file: None`, so published rows could never carry them.
    // Cached exclusions (`item: None`) contribute nothing: they are
    // already name-classified fail-safe by the watcher's planner. Scoped
    // sweeps (which did not fully discover amplifier) produce no report.
    let amplifier_root_dirs = fully_discovered_providers.contains("amplifier").then(|| {
        let mut dirs: Vec<PathBuf> = cache
            .iter()
            .filter(|(_, entry)| entry.source_name.as_deref() == Some("amplifier"))
            .filter(|(_, entry)| entry.item.as_ref().is_some_and(|i| !i.is_subagent))
            .filter_map(|(path, _)| path.parent().map(Path::to_path_buf))
            .collect();
        dirs.sort();
        dirs
    });

    // Prune: a real cache mutation that must contribute to persistence
    // accounting. During a full reconciliation, prune everything not
    // discovered (existing behavior). During a scoped refresh, only
    // prune for providers that had a full discover — other providers'
    // cache entries are untouched. Scoped-path deletions are handled
    // inline above (stat_file returns None → cache.remove).
    let cache_len_before_prune = cache.len();
    if is_full {
        cache.retain(|path, entry| {
            if discovered.contains(path) {
                return true;
            }
            match entry.source_name.as_deref() {
                Some(source_name) => failed_file_source_names.contains(source_name),
                None => file_backed_discovery_failed,
            }
        });
    } else if !fully_discovered_providers.is_empty() {
        cache.retain(|path, entry| {
            if discovered.contains(path) {
                return true;
            }
            match entry.source_name.as_deref() {
                Some(name) if fully_discovered_providers.contains(name) => {
                    failed_file_source_names.contains(name)
                }
                _ => true,
            }
        });
    }
    changed = changed.saturating_add(cache_len_before_prune - cache.len());

    let mut items: Vec<IndexedSession> = cache
        .values()
        .filter_map(|entry| entry.item.clone())
        .collect();
    for entry in direct_cache.values() {
        items.extend(entry.items.iter().cloned());
    }
    items.sort_by(|a, b| {
        b.last_activity_at
            .cmp(&a.last_activity_at)
            .then_with(|| b.key().cmp(&a.key()))
    });
    (items, changed, amplifier_root_dirs)
}

// -- Persistent parse cache (self-hosting-readiness bake-in, "kill the cold
// boot") --------------------------------------------------------------------
//
// The in-memory `FileEntry` cache above makes a WARM request fast (a sweep
// over unchanged files costs stats, not parses), but every server BOOT
// starts that cache empty -- on a real 8.7GB codex + 2.2GB claude corpus,
// the very first `warm()` sweep measured ~4-5 minutes at 99% CPU before the
// sidebar responds. This section adds disk persistence for exactly the same
// `FileEntry` map: `SessionIndex::with_ttl_and_cache_path` loads it at
// construction (pre-populating `file_cache`), and `SessionIndex::snapshot`
// opportunistically writes it back after a sweep. The EXISTING incremental
// logic in `refresh_snapshot` (above) is what makes this safe -- a loaded
// entry is only ever "used as-is" after a fresh `discover()` confirms its
// `(mtime, size)` still match; persistence changes WHERE a sweep's starting
// point comes from, never whether a stale/tampered entry can be trusted.
//
// File location: `<home>/.freshell/rust-session-cache.json` -- honoring
// `FRESHELL_HOME` then `HOME`, matching
// `crates/freshell-server/src/main.rs::resolve_home`'s precedence for the
// `.freshell` config dir this cache file lives beside.
//
// Filename: deliberately `rust-session-cache.json`, NOT `session-cache.json`
// (the legacy Node server's file, `server/session-scanner/cache.ts`). During
// the side-by-side bake-in, both servers can run concurrently against the
// SAME `~/.freshell` home; sharing one file would mean two independent
// writers (each doing its own tmp+rename) racing the same path, and the two
// formats aren't compatible anyway (this stores `FileEntry`/`IndexedSession`;
// the legacy format stores its own `SessionScanResult` shape). A distinct
// filename makes the two caches fully independent: no lock, no format
// coupling, no risk of one server's write corrupting the other's read.

/// Schema version for the persisted parse-cache file. Bump on any format
/// change so an old (or a future, if this ever needs to roll back) file is
/// cleanly discarded -- never partially or incorrectly deserialized into a
/// mismatched shape.
const CACHE_SCHEMA_VERSION: u32 = 1;

/// See "File location"/"Filename" above.
const CACHE_FILENAME: &str = "rust-session-cache.json";

/// After a sweep, save immediately once at least this many files/sources
/// changed since the last save (a cold-boot sweep over thousands of files
/// clears this on its very first sweep). Below this, saves are debounced
/// (see [`SAVE_DEBOUNCE`]) instead of writing on every small trickle of
/// changes.
const SAVE_CHANGED_THRESHOLD: u64 = 50;

/// When fewer than [`SAVE_CHANGED_THRESHOLD`] files changed, save at most
/// this often -- bounds disk-write frequency during active browsing/editing
/// without indefinitely delaying a save that IS warranted.
const SAVE_DEBOUNCE: Duration = Duration::from_secs(60);

/// On-disk shape of the persisted parse cache. `entries` is keyed by the
/// absolute file path as a `String` (not `PathBuf` -- `serde_json` object
/// keys must serialize as strings, and a lossy round-trip through
/// `to_string_lossy` is a non-issue here: a non-UTF-8 path would already be
/// unusable in this codebase's other string-keyed maps/APIs).
#[derive(serde::Serialize, serde::Deserialize)]
struct PersistedCacheFile {
    schema_version: u32,
    entries: HashMap<String, FileEntry>,
}

/// Resolve `<home>/.freshell/rust-session-cache.json`, honoring
/// `FRESHELL_HOME` then `HOME` (see the section doc comment above). `None`
/// if neither is set (or set to an empty string) -- persistence is simply
/// disabled in that case, exactly like any other optional feature with an
/// unresolvable prerequisite, never a hard error.
fn default_persist_path() -> Option<PathBuf> {
    let home = std::env::var("FRESHELL_HOME")
        .ok()
        .filter(|v| !v.is_empty())
        .or_else(|| std::env::var("HOME").ok().filter(|v| !v.is_empty()))?;
    Some(PathBuf::from(home).join(".freshell").join(CACHE_FILENAME))
}

/// Load the persisted parse cache from `path`. Tolerant of everything: a
/// missing file, unreadable/corrupt JSON, or a schema-version mismatch all
/// produce an empty cache (logged once to stderr, except for the common
/// "file doesn't exist yet" case) -- NEVER panics, NEVER fails boot. The
/// caller pre-populates `SessionIndex.file_cache` with the result; the
/// existing incremental-sweep logic in `refresh_snapshot` re-validates every
/// entry's `(mtime, size)` against a fresh `discover()` before trusting it,
/// so a stale/tampered file can only ever cause an extra re-parse, never a
/// wrong result.
fn load_cache_file(path: &Path) -> HashMap<PathBuf, FileEntry> {
    let content = match std::fs::read_to_string(path) {
        Ok(c) => c,
        Err(_) => return HashMap::new(), // missing (the common case) or unreadable
    };
    let parsed: PersistedCacheFile = match serde_json::from_str(&content) {
        Ok(p) => p,
        Err(err) => {
            eprintln!(
                "session-directory: parse cache at {} is corrupt, starting cold ({err})",
                path.display()
            );
            return HashMap::new();
        }
    };
    if parsed.schema_version != CACHE_SCHEMA_VERSION {
        eprintln!(
            "session-directory: parse cache at {} has schema_version {} (expected {}), starting cold",
            path.display(),
            parsed.schema_version,
            CACHE_SCHEMA_VERSION
        );
        return HashMap::new();
    }
    parsed
        .entries
        .into_iter()
        .filter_map(|(key, entry)| {
            let path = PathBuf::from(key);
            let has_legacy_claude_identity = entry.item.as_ref().is_some_and(|item| {
                item.provider == "claude"
                    && path.file_stem().and_then(|stem| stem.to_str())
                        != Some(item.session_id.as_str())
            });
            // Targeted semantic invalidation for the filename-identity fix:
            // discard only legacy Claude rows that cached an embedded
            // (usually parent) sessionId. Matching Claude entries, exclusions
            // (`item: None`), and every other provider remain warm.
            (!has_legacy_claude_identity).then_some((path, entry))
        })
        .collect()
}

/// Atomically persist `cache` to `path`: write the full JSON payload to a
/// sibling temp file, then `rename` it into place. A reader (or a process
/// that crashes mid-write) never observes a partially-written cache file --
/// `path` itself is untouched until the `rename`, which POSIX/most
/// filesystems perform as a single atomic directory-entry update. Creates
/// `path`'s parent directory if it doesn't exist yet (mirrors `mkdir -p
/// ~/.freshell` the legacy server's cache does at startup). Errors are
/// returned (not swallowed) so the caller can log them, but a save failure
/// NEVER propagates to any request path -- see
/// `SessionIndex::take_pending_save`'s caller in `snapshot()`.
fn save_cache_file(path: &Path, cache: &HashMap<PathBuf, FileEntry>) -> std::io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let entries: HashMap<String, FileEntry> = cache
        .iter()
        .map(|(k, v)| (k.to_string_lossy().into_owned(), v.clone()))
        .collect();
    let payload = PersistedCacheFile {
        schema_version: CACHE_SCHEMA_VERSION,
        entries,
    };
    let json = serde_json::to_string(&payload)
        .map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidData, e))?;

    let mut tmp_os = path.as_os_str().to_os_string();
    tmp_os.push(".tmp");
    let tmp_path = PathBuf::from(tmp_os);
    std::fs::write(&tmp_path, json)?;
    std::fs::rename(&tmp_path, path)?;
    Ok(())
}

